import { createClient } from "@/lib/supabase/server";
import { getMountainTimeNow } from "@/lib/data/timezone";
import { formatAnnouncementDate, formatAnnouncementTime } from "@/lib/data/announcements";
import { getWardName } from "@/lib/data/ward-settings";
import { gridColumnsFor, gridTableFor, getMeetingAttendeePeople, PERSON_AND_TEXT_ROTATION_KEYS } from "@/lib/data/rotations";
import { MEETING_TYPE_LABELS, type MeetingTypeSlug } from "@/lib/types";

/**
 * Meeting Reminder Email -- built 2026-10-31 (the user's own request:
 * "a tool in the app where the executive secretary can send an email
 * generated by the app... reminders of the upcoming meetings with
 * details about those who are assigned to the various prayers,
 * spiritual thoughts, handbook trainings, etc."). Scoped to the three
 * meeting types that actually carry these rotation-assigned roles --
 * Sacrament Meeting has no Spiritual Thought/Handbook Training concept
 * and is a fundamentally different (public, published) kind of
 * meeting, so it's deliberately left out of this tool.
 */
export const REMINDER_MEETING_TYPES: MeetingTypeSlug[] = ["bishopric-meeting", "ward-council", "youth-council"];

export interface ReminderMeetingOption {
  id: string;
  meetingTypeId: string;
  meetingTypeSlug: MeetingTypeSlug;
  label: string;
}

/**
 * The next handful of upcoming (today or later, Mountain Time,
 * non-cancelled) meetings across the three reminder-eligible types,
 * soonest first -- deliberately its own light query rather than
 * reusing getUpcomingMeetings() (lib/data/meetings.ts), which returns
 * EVERY meeting of EVERY type, past and future, plus runs three lazy
 * sweeps meant for the full Dashboard -- more than this one picker
 * needs.
 */
export async function getUpcomingReminderMeetings(): Promise<ReminderMeetingOption[]> {
  const supabase = await createClient();
  const { dateIso: today } = getMountainTimeNow();

  const { data: typeRows } = await supabase.from("meeting_types").select("id, slug").in("slug", REMINDER_MEETING_TYPES);
  const types = (typeRows ?? []) as { id: string; slug: MeetingTypeSlug }[];
  if (types.length === 0) return [];
  const slugByTypeId = new Map(types.map((t) => [t.id, t.slug]));

  const { data: meetingRows } = await supabase
    .from("meetings")
    .select("id, date, time_of_day, meeting_type_id")
    .in(
      "meeting_type_id",
      types.map((t) => t.id)
    )
    .gte("date", today)
    .eq("cancelled", false)
    .order("date", { ascending: true })
    .limit(18);

  return ((meetingRows ?? []) as { id: string; date: string; time_of_day: string | null; meeting_type_id: string }[]).map((m) => {
    const slug = slugByTypeId.get(m.meeting_type_id) ?? "bishopric-meeting";
    const when = m.time_of_day ? `${formatAnnouncementDate(m.date)} at ${formatAnnouncementTime(m.time_of_day)}` : formatAnnouncementDate(m.date);
    return {
      id: m.id,
      meetingTypeId: m.meeting_type_id,
      meetingTypeSlug: slug,
      label: `${MEETING_TYPE_LABELS[slug]} — ${when}`,
    };
  });
}

export interface MeetingRoleAssignment {
  key: string;
  label: string;
  personId: string | null;
  personName: string | null;
}

/**
 * Opening/Closing Prayer, Spiritual Thought, Handbook Training (whichever
 * apply to this meeting type -- gridColumnsFor's own per-type list,
 * lib/data/rotations.ts, the exact same catalog the Assignment Rotations
 * grid uses) resolved to real names for ONE specific meeting. Unlike
 * that grid (which deliberately shows callings, never a resolved
 * person, as of 2026-10-31), this tool's whole point is drafting
 * human-readable reminder text, so it reads the actual assigned
 * person's name directly.
 */
export async function getMeetingRoleAssignments(meetingId: string, meetingTypeSlug: MeetingTypeSlug): Promise<MeetingRoleAssignment[]> {
  const supabase = await createClient();
  const columns = gridColumnsFor(meetingTypeSlug);
  const table = gridTableFor(meetingTypeSlug);
  const roleKeys = columns.filter((c) => !PERSON_AND_TEXT_ROTATION_KEYS.has(c.key)).map((c) => c.key);
  const noteKeys = columns.filter((c) => PERSON_AND_TEXT_ROTATION_KEYS.has(c.key)).map((c) => c.key);

  const byKey = new Map<string, { id: string; name: string }>();

  if (roleKeys.length > 0) {
    const { data } = await supabase
      .from(table)
      .select("role, assigned_to_id, people(id, name)")
      .eq("meeting_id", meetingId)
      .in("role", roleKeys);
    for (const row of (data ?? []) as unknown[]) {
      const r = row as { role: string; people: { id: string; name: string }[] | { id: string; name: string } | null };
      const person = Array.isArray(r.people) ? r.people[0] : r.people;
      if (person) byKey.set(r.role, person);
    }
  }

  if (noteKeys.length > 0) {
    const { data } = await supabase
      .from("meeting_element_notes")
      .select("element_key, person_id, person:person_id(id, name)")
      .eq("meeting_id", meetingId)
      .in("element_key", noteKeys);
    for (const row of (data ?? []) as unknown[]) {
      const r = row as { element_key: string; person: { id: string; name: string }[] | { id: string; name: string } | null };
      const person = Array.isArray(r.person) ? r.person[0] : r.person;
      if (person) byKey.set(r.element_key, person);
    }
  }

  return columns.map((c) => {
    const match = byKey.get(c.key);
    return { key: c.key, label: c.label, personId: match?.id ?? null, personName: match?.name ?? null };
  });
}

export interface EmailableAttendee {
  id: string;
  name: string;
  email: string;
}

/**
 * Everyone who attends this meeting type by calling (the same
 * getMeetingAttendeePeople pool the Planning page's own fallback
 * person-picker already uses), narrowed to those who ALSO have a
 * linked login with a real email -- the user's own explicit scope: "I
 * am open to only sending to those who have log-ins that include an
 * email." `people.email` was deliberately dropped from this app's
 * schema (migration 034, see the Adding New People policy in
 * PROJECT_CONTEXT.md) -- this never reads or stores a new email
 * anywhere; `profiles.email` already exists (set once, at sign-up, by
 * Supabase Auth itself) for anyone who's actually created an account.
 */
export async function getEmailableAttendees(meetingTypeId: string): Promise<EmailableAttendee[]> {
  const supabase = await createClient();
  const attendees = await getMeetingAttendeePeople(meetingTypeId);
  if (attendees.length === 0) return [];

  const { data } = await supabase
    .from("people")
    .select("id, name, profiles:profile_id(email)")
    .in(
      "id",
      attendees.map((a) => a.id)
    )
    .not("profile_id", "is", null);

  const result: EmailableAttendee[] = [];
  for (const row of (data ?? []) as unknown[]) {
    const r = row as { id: string; name: string; profiles: { email?: string | null }[] | { email?: string | null } | null };
    const profile = Array.isArray(r.profiles) ? r.profiles[0] : r.profiles;
    if (profile?.email) result.push({ id: r.id, name: r.name, email: profile.email });
  }
  return result.sort((a, b) => a.name.localeCompare(b.name));
}

/** A sensible starting draft -- fully editable in the UI before send,
 *  this is only ever a pre-fill, never sent verbatim without a human
 *  looking at it first. */
export async function buildReminderDraft(
  meetingTypeSlug: MeetingTypeSlug,
  meetingId: string,
  meetingLabel: string
): Promise<{ subject: string; body: string }> {
  const [assignments, wardName] = await Promise.all([getMeetingRoleAssignments(meetingId, meetingTypeSlug), getWardName()]);

  const lines = assignments.map((a) => `${a.label}: ${a.personName ?? "(not yet assigned)"}`);

  // The bare /meetings/[id] route, not /planning directly (2026-10-31,
  // the user's own request: "I do want to include a line in the email
  // that includes the link to the meeting on the app") -- that route
  // already redirects each viewer to wherever they actually belong
  // (Planning for an admin, the read-only view for anyone else who
  // attends by calling), so one link works correctly for every
  // recipient regardless of their own access level, rather than
  // assuming everyone receiving this can reach Planning. Reuses
  // NEXT_PUBLIC_SITE_URL, the same env var this app's auth emails
  // already rely on, rather than a new one.
  const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || "https://ward-meeting-os.vercel.app";
  const meetingLink = `${siteUrl}/meetings/${meetingId}`;

  return {
    subject: `Reminder: ${meetingLabel}`,
    body: [
      `Hi all,`,
      "",
      `A quick reminder for our upcoming ${MEETING_TYPE_LABELS[meetingTypeSlug]}:`,
      "",
      meetingLabel,
      "",
      ...lines,
      "",
      `View the full agenda: ${meetingLink}`,
      "",
      `Thanks!`,
      `${wardName} Ward`,
    ].join("\n"),
  };
}
