import { redirect } from "next/navigation";
import Link from "next/link";
import { AppHeader } from "@/components/AppHeader";
import { getSessionUser, hasFeature } from "@/lib/supabase/get-session-user";
import {
  getUpcomingReminderMeetings,
  getMeetingRoleAssignments,
  getEmailableAttendees,
  buildReminderDraft,
} from "@/lib/data/meeting-reminder-email";
import { ReminderEmailForm } from "@/components/meeting-reminder-email/ReminderEmailForm";
import type { MeetingTypeSlug } from "@/lib/types";

/**
 * Meeting Reminder Email -- built 2026-10-31 (the user's own request:
 * "a tool in the app where the executive secretary can send an email
 * generated by the app through the associated gmail account...
 * reminders of the upcoming meetings with details about those who are
 * assigned to the various prayers, spiritual thoughts, handbook
 * trainings, etc."). Picks one of the next few Bishopric Meeting/Ward
 * Council/Youth Council occurrences, pre-fills a subject/body from that
 * meeting's own real assignments, and sends it (editable first) to
 * whichever attendees the secretary selects -- scoped to attendees who
 * have a linked login with a real email (the user's own explicit
 * choice, "I am open to only sending to those who have log-ins that
 * include an email"), since this app deliberately holds no other email
 * address for anyone.
 */
export default async function MeetingReminderEmailPage({
  searchParams,
}: {
  searchParams: Promise<{ meeting?: string }>;
}) {
  const { user, profile } = await getSessionUser();
  if (!user) redirect("/login");

  if (!hasFeature(profile, "meeting_reminder_email")) {
    return (
      <main className="mx-auto flex min-h-screen max-w-3xl flex-col px-6 py-12 sm:px-8">
        <AppHeader tag="Meeting Reminder Email" />
        <p className="mt-10 text-ink-muted">Your account doesn&rsquo;t have access to this tool.</p>
      </main>
    );
  }

  const { meeting: requestedMeetingId } = await searchParams;
  const upcoming = await getUpcomingReminderMeetings();
  const selected = upcoming.find((m) => m.id === requestedMeetingId) ?? upcoming[0] ?? null;

  return (
    <main className="mx-auto flex min-h-screen max-w-3xl flex-col gap-6 px-6 py-12 sm:px-8">
      <AppHeader tag="Meeting Reminder Email" />

      <Link href="/meeting-planning" className="text-xs text-ink-muted hover:text-ink">
        &larr; Meeting Planning
      </Link>

      <h1 className="rise-in font-display text-3xl leading-tight sm:text-4xl">Meeting Reminder Email</h1>

      {upcoming.length === 0 ? (
        <p className="text-ink-muted">No upcoming Bishopric Meeting, Ward Council, or Youth Council occurrences found.</p>
      ) : (
        <>
          <form method="get" className="flex flex-wrap items-center gap-2">
            <label className="text-xs text-ink-muted">
              Meeting
              <select
                name="meeting"
                defaultValue={selected?.id}
                className="ml-2 rounded border border-rule bg-paper px-2 py-1.5 text-sm text-ink"
              >
                {upcoming.map((m) => (
                  <option key={m.id} value={m.id}>
                    {m.label}
                  </option>
                ))}
              </select>
            </label>
            <button type="submit" className="rounded border border-rule px-3 py-1.5 text-xs text-ink hover:bg-ink/5">
              Load
            </button>
          </form>

          {selected && <ReminderSection meetingId={selected.id} meetingTypeId={selected.meetingTypeId} meetingTypeSlug={selected.meetingTypeSlug} meetingLabel={selected.label} />}
        </>
      )}
    </main>
  );
}

async function ReminderSection({
  meetingId,
  meetingTypeId,
  meetingTypeSlug,
  meetingLabel,
}: {
  meetingId: string;
  meetingTypeId: string;
  meetingTypeSlug: MeetingTypeSlug;
  meetingLabel: string;
}) {
  const [draft, assignments, attendees] = await Promise.all([
    buildReminderDraft(meetingTypeSlug, meetingId, meetingLabel),
    getMeetingRoleAssignments(meetingId, meetingTypeSlug),
    getEmailableAttendees(meetingTypeId),
  ]);

  const assignedIds = Array.from(new Set(assignments.map((a) => a.personId).filter((id): id is string => Boolean(id))));

  return (
    <ReminderEmailForm
      meetingTypeId={meetingTypeId}
      defaultSubject={draft.subject}
      defaultBody={draft.body}
      attendees={attendees}
      defaultCheckedIds={assignedIds}
    />
  );
}
